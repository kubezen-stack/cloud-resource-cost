from typing import List, Literal, Optional

from pydantic import BaseModel, Field


class Component(BaseModel):
    name: str
    aws_service: str
    sizing: str
    rationale: str
    # "catalog": backed by the curated catalog (see sources).
    # "general_knowledge": the model's own AWS knowledge: verify before relying on it.
    basis: Literal["catalog", "general_knowledge"] = "general_knowledge"
    sources: List[str] = Field(default_factory=list)
    # What the component is for; "compute" components are checked against the capacity inputs.
    role: Literal["compute", "database", "cache", "network", "storage", "monitoring", "other"] = "other"
    # Only for instance based compute: minimum and maximum (auto scaling) instance count and size.
    instance_count: Optional[int] = Field(default=None, ge=1, le=1000)
    max_instances: Optional[int] = Field(default=None, ge=1, le=1000)
    vcpu_per_instance: Optional[int] = Field(default=None, ge=1, le=512)


class CapacityInputs(BaseModel):
    """Numbers the sizing is based on. The code, not the model, checks the arithmetic."""
    peak_rps: float = Field(gt=0, le=1_000_000)
    cpu_ms_per_request: float = Field(gt=0, le=60_000)
    cpu_ms_source: Literal["customer", "assumption"] = "assumption"
    target_utilisation: float = Field(default=0.6, ge=0.3, le=0.8)
    availability_zones: int = Field(default=2, ge=1, le=6)


class AdvisorPlan(BaseModel):
    summary: str
    capacity: Optional[CapacityInputs] = None
    assumptions: List[str] = Field(default_factory=list)
    components: List[Component] = Field(min_length=1)
    open_questions: List[str] = Field(default_factory=list)
    risks: List[str] = Field(default_factory=list)


class AdvisorRequest(BaseModel):
    requirements: str = Field(min_length=20, description="Customer requirements as free text")


class SourceRef(BaseModel):
    reference: str
    score: float


class AdvisorResponse(BaseModel):
    plan: AdvisorPlan
    sources: List[SourceRef]
    model: str
    # Findings of the automatic checks (capacity arithmetic, zones, ...). Empty means all passed.
    warnings: List[str] = Field(default_factory=list)
    note: str = (
        "Starting-point recommendation generated by an AI model. Components with basis "
        "'general_knowledge' come from the model's own knowledge and must be verified. "
        "Validate sizing with a load test. No prices are estimated."
    )
