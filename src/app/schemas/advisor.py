from typing import List, Literal

from pydantic import BaseModel, Field


class Component(BaseModel):
    name: str
    aws_service: str
    sizing: str
    rationale: str
    # "catalog": backed by the curated catalog (see sources).
    # "general_knowledge": the model's own AWS knowledge: verify before relying on it.
    basis: Literal["catalog", "general_knowledge"] = "general_knowledge"
    sources: List[str] = Field(default_factory=list)


class AdvisorPlan(BaseModel):
    summary: str
    assumptions: List[str] = Field(default_factory=list)
    components: List[Component] = Field(min_length=1)
    open_questions: List[str] = Field(default_factory=list)
    risks: List[str] = Field(default_factory=list)


class AdvisorRequest(BaseModel):
    requirements: str = Field(min_length=20, description="Customer requirements as free text")


class SourceRef(BaseModel):
    reference: str
    score: float


class AdvisorResponse(BaseModel):
    plan: AdvisorPlan
    sources: List[SourceRef]
    model: str
    note: str = (
        "Starting-point recommendation generated by an AI model. Components with basis "
        "'general_knowledge' come from the model's own knowledge and must be verified. "
        "Validate sizing with a load test. No prices are estimated."
    )
